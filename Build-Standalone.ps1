#Requires -Version 5.1
[CmdletBinding()]
param([string]$OutputDirectory = $PSScriptRoot)

$ErrorActionPreference = 'Stop'
$corePath = Join-Path $PSScriptRoot 'PZ_Memory_Configurator.ps1'
$core = [System.IO.File]::ReadAllText($corePath, [System.Text.Encoding]::UTF8)
$tokens = $null
$parseErrors = $null
$null = [System.Management.Automation.Language.Parser]::ParseInput($core, [ref]$tokens, [ref]$parseErrors)
if ($parseErrors.Count) { throw ($parseErrors | Out-String) }
if ($core -match '(?m)^# PZ_CONFIGURATOR_(?:SOURCE|END)\r?$') { throw 'The source contains a reserved packaging marker.' }

# 核心以可讀原始碼內嵌，不壓縮、不下載程式，也不建立暫存 .ps1。
$template = @'
@echo off
setlocal DisableDelayedExpansion
chcp 65001 >nul
rem Generated by Build-Standalone.ps1. Edit the shared .ps1 source instead.
set "PZ_CONFIGURATOR_SELF=%~f0"
powershell.exe -NoLogo -NoProfile -ExecutionPolicy Bypass -Command "try { $ErrorActionPreference='Stop'; $parts=[System.IO.File]::ReadAllText($env:PZ_CONFIGURATOR_SELF,[System.Text.Encoding]::UTF8) -split '(?m)^# PZ_CONFIGURATOR_(?:SOURCE|END)\r?$',3; if($parts.Count -ne 3) { throw 'Embedded program is incomplete. Download this BAT again.' }; & ([scriptblock]::Create($parts[1])) -Language '__LANGUAGE__'; if(-not $?) { exit 1 } } catch { Write-Error -ErrorRecord $_ -ErrorAction Continue; exit 1 }"
set "result=%errorlevel%"
if not "%result%"=="0" echo __FAILURE__
pause
exit /b %result%
# PZ_CONFIGURATOR_SOURCE
'@

$outputPath = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($OutputDirectory)
$null = [System.IO.Directory]::CreateDirectory($outputPath)
$encoding = New-Object System.Text.UTF8Encoding($false)
foreach ($language in @('zh-TW', 'en-US')) {
    $suffix = if ($language -eq 'zh-TW') { 'ZH_TW' } else { 'EN_US' }
    $failure = if ($language -eq 'zh-TW') {
        '工具未能完成操作，請查看上方錯誤。若公司或學校禁止執行腳本，請聯絡管理員。'
    } else {
        'The operation did not complete. Check the error above. If scripts are blocked by your organization, contact your administrator.'
    }
    $header = $template.Replace('__LANGUAGE__', $language).Replace('__FAILURE__', $failure)
    $content = ($header + "`n" + $core + "`n# PZ_CONFIGURATOR_END`n").Replace("`r`n", "`n").Replace("`n", "`r`n")
    $destination = Join-Path $outputPath "PZ_Memory_Configurator_$suffix.bat"
    [System.IO.File]::WriteAllText($destination, $content, $encoding)
    Write-Host $destination
}
